#!/usr/bin/env bash
# ClassroomGuard - first-time install on a college server (Ubuntu 22.04/24.04 or any Linux
# with Docker Engine + Compose v2). Safe to re-run: existing .env values are kept.
#
#   sudo ./scripts/install.sh
#
# Unattended: SITE_ADDRESS=cg.college.edu ADMIN_EMAIL=it@college.edu ADMIN_PASSWORD='...' ./scripts/install.sh
#
# What it does: checks prerequisites, writes .env with random secrets, prepares storage,
# builds and starts the stack behind HTTPS, waits until it is healthy, then creates the
# first super admin account.
set -euo pipefail
cd "$(dirname "$0")/.."

say()  { printf '\n\033[1;34m==> %s\033[0m\n' "$*"; }
fail() { printf '\n\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

# ── Prerequisites ──────────────────────────────────────────────────────────────
say "Checking prerequisites"
command -v docker >/dev/null || fail "Docker is not installed. See https://docs.docker.com/engine/install/ubuntu/"
docker compose version >/dev/null 2>&1 || fail "Docker Compose v2 is missing (package docker-compose-plugin)."
command -v openssl >/dev/null || fail "openssl is required to generate secrets."
docker info >/dev/null 2>&1 || fail "Cannot talk to Docker. Run with sudo or add this user to the docker group."

WITH_AI=false
if command -v nvidia-smi >/dev/null && nvidia-smi >/dev/null 2>&1; then
  if docker run --rm --gpus all --entrypoint true busybox >/dev/null 2>&1; then
    WITH_AI=true
    echo "NVIDIA GPU available to Docker - the AI engine will be installed."
  else
    echo "NVIDIA GPU found but Docker cannot use it: install the NVIDIA Container Toolkit to run the AI engine here."
  fi
else
  echo "No NVIDIA GPU - installing the web platform only (run the AI engine on a GPU machine)."
fi

# ── .env ───────────────────────────────────────────────────────────────────────
set_env() {  # set_env KEY VALUE - adds the key only if .env does not have it yet
  grep -q "^$1=" .env 2>/dev/null || echo "$1=$2" >> .env
}

if [ ! -f .env ]; then
  say "Creating .env"
  SITE="${SITE_ADDRESS:-}"
  [ -n "$SITE" ] || read -rp "Address users will open (host name or IP, e.g. classroomguard.college.edu): " SITE
  [ -n "$SITE" ] || fail "An address is required."
  cat > .env <<EOF
# Generated by scripts/install.sh on $(date -u +%Y-%m-%dT%H:%MZ). Keep this file private.
COMPOSE_FILE=docker-compose.yml:docker-compose.https.yml
APP_ENV=production
SITE_ADDRESS=$SITE
CADDY_TLS=internal
FRONTEND_URL=https://$SITE
ALLOWED_ORIGINS=["https://$SITE"]
EOF
fi
set_env POSTGRES_PASSWORD "$(openssl rand -hex 24)"
set_env JWT_SECRET "$(openssl rand -hex 32)"
set_env AI_SERVICE_TOKEN "$(openssl rand -hex 32)"
set_env ACCESS_TOKEN_EXPIRE_MINUTES 60
if $WITH_AI && ! grep -q "^COMPOSE_PROFILES=" .env; then echo "COMPOSE_PROFILES=ai" >> .env; fi
chmod 600 .env

# ── Storage (containers run as uid 1000) ───────────────────────────────────────
say "Preparing storage"
mkdir -p storage/evidence storage/frames storage/recordings storage/uploads backups
chown -R 1000:1000 storage 2>/dev/null   || echo "WARNING: could not hand storage/ to uid 1000 - run as root, or evidence uploads will fail"

if $WITH_AI && [ ! -f ai/models/exam_detector.pt ]; then
  fail "AI model missing: copy exam_detector.pt and yolov8m-pose.pt into ai/models/ (see ai/README.md), then re-run."
fi

# ── Build and start ────────────────────────────────────────────────────────────
say "Building and starting ClassroomGuard (first build takes several minutes)"
docker compose up -d --build

say "Waiting for the API to become healthy"
for _ in $(seq 1 60); do
  if [ "$(docker inspect -f '{{.State.Health.Status}}' "$(docker compose ps -q backend)" 2>/dev/null)" = "healthy" ]; then
    break
  fi
  sleep 5
done
[ "$(docker inspect -f '{{.State.Health.Status}}' "$(docker compose ps -q backend)")" = "healthy" ] \
  || fail "API did not become healthy. Check: docker compose logs backend"

# ── First admin ────────────────────────────────────────────────────────────────
say "Create the first super admin account"
if [ -n "${ADMIN_EMAIL:-}" ] && [ -n "${ADMIN_PASSWORD:-}" ]; then
  # Unattended install: ADMIN_EMAIL=... ADMIN_PASSWORD=... ./scripts/install.sh
  docker compose exec -T -e ADMIN_EMAIL="$ADMIN_EMAIL" -e ADMIN_PASSWORD="$ADMIN_PASSWORD" backend python -m backend.create_admin
else
  docker compose exec backend python -m backend.create_admin     || echo "Create it later with: docker compose exec backend python -m backend.create_admin"
fi

SITE=$(grep '^SITE_ADDRESS=' .env | cut -d= -f2)
say "Done. Open https://$SITE"
cat <<EOF

Next steps (see docs/DEPLOY_ONPREM.md):
  * Trust the HTTPS certificate, or install the college certificate (CADDY_TLS in .env)
  * Configure SMTP_* in .env for password-reset emails, then: docker compose up -d
  * Schedule backups:  sudo crontab -e  ->  0 2 * * * $(pwd)/scripts/backup.sh
EOF
